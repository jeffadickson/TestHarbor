using Microsoft.Extensions.DependencyInjection;
using NUnit.Framework;
using TestHarbor.NUnit.Injection;

namespace TestHarbor.Example.Injection;

/// <summary>Exercises NUnit data generation while services remain execution-time dependencies.</summary>
/// <param name="endpoint">Attempt-local unkeyed endpoint.</param>
[HarborInjectedFixture(typeof(KeyedProfile)), Parallelizable(ParallelScope.All)]
public sealed class InjectionDataCompatibilityTests(KeyedEndpoint endpoint)
{
    /// <summary>Combines ordinary Values parameters on both sides of an injected service.</summary>
    /// <param name="quantity">Generated quantity data.</param>
    /// <param name="same">The fixture's scoped endpoint.</param>
    /// <param name="product">Generated product data.</param>
    [Test, Combinatorial]
    public void Values([Values(1, 2)] int quantity, [FromServices] KeyedEndpoint same,
        [Values("book", "pen")] string product)
    {
        Assert.That(same, Is.SameAs(endpoint));
        Assert.That(same.Requests, Is.Empty);
        Assert.That(quantity, Is.InRange(1, 2));
        Assert.That(product, Is.EqualTo("book").Or.EqualTo("pen"));
        same.Requests.Add(product);
    }
    /// <summary>Preserves NUnit range stepping with a keyed service before the data.</summary>
    /// <param name="primary">Keyed endpoint selected at execution time.</param>
    /// <param name="quantity">Even quantities generated by NUnit.</param>
    [Test]
    public void Range([FromKeyedServices("primary")] KeyedEndpoint primary, [Range(2, 6, 2)] int quantity)
    {
        Assert.That(primary.Name, Is.EqualTo("primary"));
        Assert.That(quantity, Is.AnyOf(2, 4, 6));
        Assert.That(endpoint.Requests, Is.Empty);
        endpoint.Requests.Add(quantity.ToString());
    }

    /// <summary>Checks floating-point range data retains its original parameter type.</summary>
    /// <param name="fraction">Half-step values generated by NUnit.</param>
    /// <param name="same">Scoped dependency following the data.</param>
    [Test]
    public void FractionalRange([Range(0.5, 1.5, 0.5)] double fraction, [FromServices] KeyedEndpoint same)
    {
        Assert.That(same, Is.SameAs(endpoint));
        Assert.That(fraction, Is.AnyOf(0.5, 1.0, 1.5));
    }
    /// <summary>Lets NUnit generate pairwise coverage while excluding the service from the data dimensions.</summary>
    /// <param name="region">Deployment region dimension.</param>
    /// <param name="same">Scoped endpoint outside the generated data dimensions.</param>
    /// <param name="tier">Subscription tier dimension.</param>
    /// <param name="cached">Cache-enabled dimension.</param>
    [Test, Pairwise]
    public void Pairwise([Values("east", "west")] string region, [FromServices] KeyedEndpoint same,
        [Values(1, 2)] int tier, [Values(false, true)] bool cached)
    {
        Assert.That(same, Is.SameAs(endpoint));
        Assert.That(region, Is.EqualTo("east").Or.EqualTo("west"));
        Assert.That(tier, Is.AnyOf(1, 2));
        TestContext.Out.WriteLine("PAIRWISE:" + System.Text.Json.JsonSerializer.Serialize(new object[] { region, tier, cached }));
    }
    /// <summary>Pairs data columns sequentially without treating the keyed service as a column.</summary>
    /// <param name="quantity">Ordered quantity column.</param>
    /// <param name="primary">Key-selected service between data columns.</param>
    /// <param name="total">Matching total column.</param>
    [Test, Sequential]
    public void Sequential([Values(1, 2, 3)] int quantity,
        [FromKeyedServices("primary")] KeyedEndpoint primary, [Values(100, 200, 300)] int total)
    {
        Assert.That(primary.Name, Is.EqualTo("primary"));
        Assert.That(total, Is.EqualTo(quantity * 100));
    }
    /// <summary>Supplies asynchronously obtained discovery data without creating any services.</summary>
    /// <returns>Two named ordinary NUnit data rows.</returns>
    public static async Task<IEnumerable<TestCaseData>> TaskRows()
    {
        await Task.Yield();
        return [new TestCaseData(1).SetName("TaskSourceOne"), new TestCaseData(2).SetName("TaskSourceTwo")];
    }

    /// <summary>Supplies asynchronously streamed discovery data without depending on an injection scope.</summary>
    /// <returns>Two named ordinary NUnit data rows.</returns>
    public static async IAsyncEnumerable<TestCaseData> StreamRows()
    {
        await Task.Yield();
        yield return new TestCaseData(3).SetName("StreamSourceThree");
        yield return new TestCaseData(4).SetName("StreamSourceFour");
    }

    /// <summary>Combines an awaited data source with a trailing scoped service.</summary>
    /// <param name="input">Source-provided ordinary data.</param>
    /// <param name="same">Execution-time dependency.</param>
    [TestCaseSource(nameof(TaskRows))]
    public void TaskSource(int input, [FromServices] KeyedEndpoint same)
    { Assert.That(input, Is.AnyOf(1, 2)); Assert.That(same, Is.SameAs(endpoint)); }

    /// <summary>Combines an asynchronous stream source with a leading keyed service.</summary>
    /// <param name="primary">Execution-time keyed dependency.</param>
    /// <param name="input">Source-provided ordinary data.</param>
    [TestCaseSource(nameof(StreamRows))]
    public void StreamSource([FromKeyedServices("primary")] KeyedEndpoint primary, int input)
    { Assert.That(input, Is.AnyOf(3, 4)); Assert.That(primary.Name, Is.EqualTo("primary")); }
    /// <summary>Uses NUnit's automatic enum and nullable Boolean Values expansion.</summary>
    /// <param name="mode">Every defined shipping mode.</param>
    /// <param name="same">Service excluded from the generated dimensions.</param>
    /// <param name="enabled">Null, false and true generated by NUnit.</param>
    [Test, Combinatorial]
    public void AutomaticValues([Values] ShippingMode mode, [FromServices] KeyedEndpoint same, [Values] bool? enabled)
    {
        Assert.That(same, Is.SameAs(endpoint));
        Assert.That(Enum.IsDefined(mode), Is.True);
        TestContext.Out.WriteLine("AUTOMATIC:" + System.Text.Json.JsonSerializer.Serialize(new object?[] { (int)mode, enabled }));
    }

    /// <summary>Preserves NUnit's conversion from attribute numeric literals into decimal data.</summary>
    /// <param name="amount">Decimal amount converted by NUnit.</param>
    /// <param name="same">Scoped service between numeric data parameters.</param>
    /// <param name="cents">Expected exact decimal result in cents.</param>
    [TestCase(1.25, 125), TestCase(2.5, 250)]
    public void DecimalConversion(decimal amount, [FromServices] KeyedEndpoint same, int cents)
    { Assert.That(same, Is.SameAs(endpoint)); Assert.That(amount * 100m, Is.EqualTo((decimal)cents)); }

    /// <summary>Keeps null data distinct from an injected dependency.</summary>
    /// <param name="input">Nullable case data.</param>
    /// <param name="same">Non-null scoped dependency.</param>
    [TestCase(null), TestCase(7)]
    public void NullableData(int? input, [FromServices] KeyedEndpoint same)
    { Assert.That(input, Is.Null.Or.EqualTo(7)); Assert.That(same, Is.SameAs(endpoint)); }

}

/// <summary>Verifies NUnit awaits ValueTask return values before ordinary teardown.</summary>
[HarborInjectedFixture(typeof(KeyedProfile))]
public sealed class InjectionValueTaskTests
{
    /// <summary>Records completion after the asynchronous continuation.</summary>
    private bool completed;

    /// <summary>Returns an awaited value while combining keyed injection with expected-result data.</summary>
    /// <param name="primary">Keyed dependency supplied at invocation.</param>
    /// <param name="input">Ordinary data doubled by the body.</param>
    /// <returns>Twice the input, compared by NUnit with ExpectedResult.</returns>
    [TestCase(10, ExpectedResult = 20), TestCase(20, ExpectedResult = 40)]
    public async ValueTask<int> ReturnsValue([FromKeyedServices("primary")] KeyedEndpoint primary, int input)
    {
        await Task.Yield();
        Assert.That(primary.Name, Is.EqualTo("primary"));
        completed = true;
        return input * 2;
    }

    /// <summary>Checks a non-generic ValueTask is also awaited before teardown.</summary>
    /// <param name="endpoint">Unkeyed service injected into the body.</param>
    /// <returns>A completion signal after an asynchronous continuation.</returns>
    [Test]
    public async ValueTask WithoutResult([FromServices] KeyedEndpoint endpoint)
    {
        await Task.Yield();
        Assert.That(endpoint.Name, Is.EqualTo("default"));
        completed = true;
    }

    /// <summary>Fails if NUnit proceeds to teardown before the awaited method finishes.</summary>
    [TearDown]
    public void VerifyAwaited() => Assert.That(completed, Is.True);
}

/// <summary>Defines reusable NUnit assertions for a dependency type chosen by a concrete fixture.</summary>
/// <typeparam name="T">Service type closed by the inheriting fixture.</typeparam>
/// <param name="expected">Dependency received by the concrete fixture constructor.</param>
public abstract class GenericInjectionContract<T>(T expected) where T : class
{
    /// <summary>Verifies an inherited generic-class parameter resolves to the concrete service type.</summary>
    /// <param name="actual">Dependency bound through the inherited method descriptor.</param>
    [Test]
    public void InheritedIdentity([FromServices] T actual) => Assert.That(actual, Is.SameAs(expected));

    /// <summary>Preserves ordinary data binding alongside a closed generic service parameter.</summary>
    /// <param name="input">Ordinary NUnit case data.</param>
    /// <param name="actual">Concrete service selected by the generic base class.</param>
    [TestCase(7)]
    public void InheritedData(int input, [FromServices] T actual)
    { Assert.That(input, Is.EqualTo(7)); Assert.That(actual, Is.SameAs(expected)); }
}

/// <summary>Closes a generic contract while retaining a non-generic concrete fixture.</summary>
/// <param name="endpoint">Service forwarded to the base contract.</param>
[HarborInjectedFixture(typeof(KeyedProfile))]
public sealed class InjectionGenericContractTests(KeyedEndpoint endpoint) : GenericInjectionContract<KeyedEndpoint>(endpoint);

